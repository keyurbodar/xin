export type FileIconSet = "dark" | "light"

/** A Symbols icon's path under /file-icons/<set>/: a folder by its name, a file by its exact name, then its longest compound extension (`d.ts` before `ts`), else the generic file or folder. */
export function fileIcon(name: string, folder: boolean): string {
  const lower = name.toLowerCase()
  if (folder) return FOLDERS[lower] ?? "folders/folder"
  const named = NAMES[lower]
  if (named !== undefined) return named
  for (let dot = lower.indexOf(".", 1); dot !== -1; dot = lower.indexOf(".", dot + 1)) {
    const icon = EXTENSIONS[lower.slice(dot + 1)]
    if (icon !== undefined) return icon
  }
  return "files/document"
}

export function fileIconUrl(name: string, folder: boolean, set: FileIconSet): string {
  return `/file-icons/${set}/${fileIcon(name, folder)}.svg`
}
